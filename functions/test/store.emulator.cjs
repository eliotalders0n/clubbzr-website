  const o = await checkout(buyer, checkoutInput(await makeListing(), { paymentRail: 'ZMW', phone: '260971234567', operator: 'mtn' }))
  async function send(payload) {
    const rawBody = Buffer.from(JSON.stringify(payload))
    const key = createHash('sha256').update(process.env.LENCO_SECRET_KEY).digest('hex')
    const signature = createHmac('sha512', key).update(rawBody).digest('hex')
    const response = { code: 0, status(code) { this.code = code; return this }, send() { return this } }
    await lencoPointsWebhook({ method: 'POST', rawBody, body: payload, get: () => signature }, response)
    assert.equal(response.code, 200)
  }
  await send({ event: 'collection.successful', data: paymentData(o.orderId) })
  assert.equal((await get('trades', o.orderId)).status, 'completed')
  assert.equal((await get('balances', buyer.uid)).available, 100000)
